VALID_RANKS = {"Iron", "Bronze", "Silver", "Gold", "Platinum", "Diamond", "Ascendant", "Immortal", "Radiant"}

def seed_bracket():
    # Safe, idempotent: never deletes or resets existing matches.
    with db() as con:
        for rnd, count in ((1, 4), (2, 2), (3, 1)):
            for slot in range(1, count + 1):
                con.execute("INSERT INTO matches(round_no,slot_no) VALUES(?,?) ON CONFLICT(round_no,slot_no) DO NOTHING", (rnd, slot))

def migrate_team_number():
    # Non-destructive migration: adds the public slot field to older databases.
    with db() as con:
        if con.is_postgres:
            con.execute("ALTER TABLE teams ADD COLUMN IF NOT EXISTS team_number INTEGER")
            con.execute("ALTER TABLE teams ADD COLUMN IF NOT EXISTS team_color TEXT NOT NULL DEFAULT '#22C55E'")
            con.execute("CREATE UNIQUE INDEX IF NOT EXISTS teams_team_number_unique ON teams(team_number)")
        else:
            cols = [r[1] for r in con.execute("PRAGMA table_info(teams)").fetchall()]
            if "team_number" not in cols:
                con.execute("ALTER TABLE teams ADD COLUMN team_number INTEGER")
            if "team_color" not in cols:
                con.execute("ALTER TABLE teams ADD COLUMN team_color TEXT NOT NULL DEFAULT '#22C55E'")
            con.execute("CREATE UNIQUE INDEX IF NOT EXISTS teams_team_number_unique ON teams(team_number)")

def migrate_private_ranks():
    """Adds private peak-rank fields without deleting existing applications."""
    rank_columns = ("rank1", "rank2", "rank3", "rank4", "rank5", "substitute_rank")
    with db() as con:
        if con.is_postgres:
            for col in rank_columns:
                con.execute(f"ALTER TABLE teams ADD COLUMN IF NOT EXISTS {col} TEXT NOT NULL DEFAULT 'Unranked'")
        else:
            cols = [r[1] for r in con.execute("PRAGMA table_info(teams)").fetchall()]
            for col in rank_columns:
                if col not in cols:
                    con.execute(f"ALTER TABLE teams ADD COLUMN {col} TEXT NOT NULL DEFAULT 'Unranked'")

init_db()
migrate_team_number()
migrate_private_ranks()
init_tournament_tables()
seed_bracket()

def load_matches(con):
    rows = con.execute("""SELECT m.*, ('Takım ' || a.team_number) AS a_name, ('Takım ' || b.team_number) AS b_name,
        a.team_color AS a_color, b.team_color AS b_color
        FROM matches m LEFT JOIN teams a ON a.id=m.team_a LEFT JOIN teams b ON b.id=m.team_b
        ORDER BY m.round_no,m.slot_no""").fetchall()
    rounds = {1: [], 2: [], 3: []}
    for m in rows:
        if m["round_no"] in rounds:
            rounds[m["round_no"]].append(m)
    return rows, rounds

@app.route("/")
def index():
    with db() as con:
        teams = con.execute("SELECT * FROM teams WHERE status='approved' ORDER BY COALESCE(team_number, 99), class_name").fetchall()
        pending_count = con.execute("SELECT COUNT(*) AS count FROM teams WHERE status='pending'").fetchone()["count"]
        results = con.execute("""SELECT r.*,('Takım ' || a.team_number) AS a_name,('Takım ' || b.team_number) AS b_name
            FROM results r JOIN teams a ON a.id=r.team_a JOIN teams b ON b.id=r.team_b ORDER BY r.id DESC""").fetchall()
        matches, rounds = load_matches(con)
        announcements = con.execute("SELECT * FROM announcements ORDER BY id DESC").fetchall()
        applications_open = get_setting(con, "applications_open", "true") == "true"
    return render_template("index.html", teams=teams, results=results, rounds=rounds,
                           matches=matches, announcements=announcements, pending_count=pending_count,
                           applications_open=applications_open)

