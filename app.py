@app.route("/basvuru", methods=["GET", "POST"])
def apply():
    with db() as con:
        applications_open = get_setting(con, "applications_open", "true") == "true"
    if not applications_open:
        if request.method == "POST":
            flash("Takım başvuruları şu anda kapalı.", "error")
        return render_template("apply.html", applications_open=False)
    if request.method == "POST":
        fields = ["class_name","captain","contact","player1","player2","player3","player4","player5","substitute"]
        values = [request.form.get(k, "").strip() for k in fields]
        rank_options = VALID_RANKS
        rank_values = [request.form.get(k, "").strip() for k in ("rank1", "rank2", "rank3", "rank4", "rank5", "substitute_rank")]
        if any(rank not in rank_options for rank in rank_values):
            flash("Lütfen her oyuncu için geçerli bir Peak Rank seçin.", "error")
            return render_template("apply.html", applications_open=True)
        note = request.form.get("note", "").strip()
        if any(not v for v in values):
            flash("Lütfen zorunlu alanların tamamını doldurun.", "error")
            return render_template("apply.html", applications_open=True)
        try:
            with db() as con:
                con.execute("""INSERT INTO teams
                    (class_name,captain,contact,player1,player2,player3,player4,player5,substitute,rank1,rank2,rank3,rank4,rank5,substitute_rank,note)
                    VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""", values + rank_values + [note])
            flash("Başvurun alındı! Yönetici onayından sonra takım listesinde görünecek.", "success")
            return redirect(url_for("apply"))
        except Exception as e:
            if "unique" in str(e).lower() or "duplicate" in str(e).lower():
                flash("Bu sınıf için daha önce başvuru yapılmış.", "error")
            else:
                app.logger.exception("Başvuru kaydedilemedi")
                flash("Başvuru kaydedilemedi. Lütfen daha sonra tekrar deneyin.", "error")
    return render_template("apply.html", applications_open=True)

def admin_authorized():
    if session.get("admin_logged_in"):
        return True
    expected = os.environ.get("ADMIN_KEY", "")
    supplied = request.form.get("key", "") or request.args.get("key", "")
    if expected and supplied == expected:
        session["admin_logged_in"] = True
        return True
    return False

def advance_winner(con, match, winner):
    if match["round_no"] >= 3:
        return
    next_round = match["round_no"] + 1
    next_slot = (match["slot_no"] + 1) // 2
    column = "team_a" if match["slot_no"] % 2 else "team_b"
    # Do not overwrite an already-played next-round match silently.
    nxt = con.execute("SELECT * FROM matches WHERE round_no=? AND slot_no=?", (next_round, next_slot)).fetchone()
    if nxt:
        if nxt["status"] == "completed":
            raise ValueError("Sonraki tur maçı tamamlanmış; önce o maçın sonucunu düzeltin.")
        other_col = "team_b" if column == "team_a" else "team_a"
        if nxt[other_col] == winner:
            pass
        con.execute(f"UPDATE matches SET {column}=? WHERE round_no=? AND slot_no=?", (winner, next_round, next_slot))
    else:
        con.execute(f"INSERT INTO matches(round_no,slot_no,{column}) VALUES(?,?,?)", (next_round,next_slot,winner))

@app.route("/yonetim", methods=["GET", "POST"])
def admin():
    if not admin_authorized():
        return render_template("admin_login.html")
    if request.method == "POST":
        action = request.form.get("action")
        try:
            with db() as con:
                if action in ("approve", "reject"):
                    status = "approved" if action == "approve" else "rejected"
                    con.execute("UPDATE teams SET status=? WHERE id=?", (status, request.form.get("team_id")))
                    flash("Başvuru durumu güncellendi.", "success")
                elif action == "edit_team":
                    tid = int(request.form["team_id"])
                    fields = ["class_name", "captain", "contact", "player1", "player2", "player3", "player4", "player5", "substitute"]
                    vals = [request.form.get(k, "").strip() for k in fields]
                    rank_fields = ["rank1", "rank2", "rank3", "rank4", "rank5", "substitute_rank"]
                    rank_vals = [request.form.get(k, "Unranked").strip() for k in rank_fields]
                    note = request.form.get("note", "").strip()
                    if any(not v for v in vals):
                        raise ValueError("Zorunlu alanları doldurun.")
                    con.execute("UPDATE teams SET class_name=?,captain=?,contact=?,player1=?,player2=?,player3=?,player4=?,player5=?,substitute=?,rank1=?,rank2=?,rank3=?,rank4=?,rank5=?,substitute_rank=?,note=? WHERE id=?", vals+rank_vals+[note,tid])
                    flash("Takım bilgileri güncellendi.", "success")
                elif action == "delete_team":
                    tid = int(request.form["team_id"])
                    # Remove the team's references and any match results. Keep the bracket slots themselves.
                    con.execute("UPDATE matches SET team_a=NULL,score_a=NULL,score_b=NULL,status='upcoming' WHERE team_a=?", (tid,))
                    con.execute("UPDATE matches SET team_b=NULL,score_a=NULL,score_b=NULL,status='upcoming' WHERE team_b=?", (tid,))
                    con.execute("DELETE FROM results WHERE team_a=? OR team_b=?", (tid,tid))
                    con.execute("DELETE FROM teams WHERE id=?", (tid,))
                    flash("Takım ve ilişkili tüm kayıtları silindi.", "success")
                elif action == "applications_toggle":
                    new_value = "false" if get_setting(con, "applications_open", "true") == "true" else "true"
                    set_setting(con, "applications_open", new_value)
                    flash("Başvurular " + ("açıldı." if new_value == "true" else "kapatıldı."), "success")
                elif action == "set_color":
                    tid = int(request.form["team_id"])
                    color_key = request.form.get("team_color", "")
                    if color_key not in TEAM_COLORS:
                        raise ValueError("Geçerli bir takım rengi seçin.")
                    con.execute("UPDATE teams SET team_color=? WHERE id=?", (TEAM_COLORS[color_key], tid))
                    flash("Takım rengi güncellendi.", "success")
                elif action == "assign_number":
                    tid = int(request.form["team_id"])
                    raw = request.form.get("team_number", "").strip()
                    number = int(raw) if raw else None
                    if number is not None and not 1 <= number <= 8:
                        raise ValueError("Takım numarası 1 ile 8 arasında olmalı.")
                    con.execute("UPDATE teams SET team_number=NULL WHERE team_number=? AND id<>?", (number,tid)) if number is not None else None
                    con.execute("UPDATE teams SET team_number=? WHERE id=?", (number,tid))
                    flash("Takım numarası güncellendi.", "success")
                elif action == "save_match":
                    rnd, slot = int(request.form["round_no"]), int(request.form["slot_no"])
                    ta, tb = request.form.get("team_a") or None, request.form.get("team_b") or None
                    if rnd not in (1,2,3) or slot < 1 or slot > {1:4,2:2,3:1}[rnd] or (ta and ta == tb):
                        raise ValueError()
                    con.execute("""INSERT INTO matches(round_no,slot_no,team_a,team_b,match_date,match_time,status,note)
                        VALUES(?,?,?,?,?,?,?,?) ON CONFLICT(round_no,slot_no) DO UPDATE SET
                        team_a=excluded.team_a,team_b=excluded.team_b,match_date=excluded.match_date,
                        match_time=excluded.match_time,status=excluded.status,note=excluded.note""",
                        (rnd,slot,ta,tb,request.form.get("match_date",""),request.form.get("match_time",""),
                         request.form.get("status","upcoming"),request.form.get("note","").strip()))
                    flash("Eşleşme ve maç bilgileri kaydedildi.", "success")
                elif action == "match_result":
                    mid, sa, sb = int(request.form["match_id"]), int(request.form["score_a"]), int(request.form["score_b"])
                    if min(sa,sb) < 0 or max(sa,sb) > 2 or sa == sb or max(sa,sb) != 2:
                        raise ValueError()
                    match = con.execute("SELECT * FROM matches WHERE id=?", (mid,)).fetchone()
                    if not match or not match["team_a"] or not match["team_b"]:
                        raise ValueError()
                    winner = match["team_a"] if sa > sb else match["team_b"]
                    # Prevent editing a result if a downstream match has already been completed.
                    if match["round_no"] < 3:
                        nr, ns = match["round_no"] + 1, (match["slot_no"] + 1)//2
                        nxt = con.execute("SELECT * FROM matches WHERE round_no=? AND slot_no=?", (nr,ns)).fetchone()
                        col = "team_a" if match["slot_no"] % 2 else "team_b"
                        if nxt and nxt["status"] == "completed" and nxt[col] != winner:
                            raise ValueError("Sonraki tur tamamlanmış; önce sonraki tur sonucunu sıfırlayın.")
                    con.execute("UPDATE matches SET score_a=?,score_b=?,status='completed' WHERE id=?", (sa,sb,mid))
                    advance_winner(con, match, winner)
                    flash("Skor kaydedildi; kazanan sonraki tura aktarıldı.", "success")
                elif action == "delete_match_result":
                    mid = int(request.form["match_id"])
                    match = con.execute("SELECT * FROM matches WHERE id=?", (mid,)).fetchone()
                    if match:
                        if match["round_no"] < 3:
                            nr, ns = match["round_no"] + 1, (match["slot_no"] + 1)//2
                            col = "team_a" if match["slot_no"] % 2 else "team_b"
                            nxt = con.execute("SELECT * FROM matches WHERE round_no=? AND slot_no=?", (nr,ns)).fetchone()
                            if nxt and nxt["status"] == "completed":
                                raise ValueError("Önce sonraki tur maçının sonucunu sıfırlayın.")
                            if nxt and match["score_a"] is not None and match["score_b"] is not None:
                                prior_winner = match["team_a"] if match["score_a"] > match["score_b"] else match["team_b"]
                                con.execute(f"UPDATE matches SET {col}=NULL WHERE round_no=? AND slot_no=? AND {col}=?", (nr,ns,prior_winner))
                        con.execute("UPDATE matches SET score_a=NULL,score_b=NULL,status='upcoming' WHERE id=?", (mid,))
                        flash("Maç skoru sıfırlandı.", "success")
                elif action == "announcement":
                    title, body = request.form.get("title","").strip(), request.form.get("body","").strip()
                    if not title or not body:
                        raise ValueError()
                    con.execute("INSERT INTO announcements(title,body) VALUES(?,?)", (title,body))
                    flash("Duyuru yayımlandı.", "success")
                elif action == "edit_announcement":
                    aid = int(request.form["announcement_id"])
                    title, body = request.form.get("title", "").strip(), request.form.get("body", "").strip()
                    if not title or not body:
                        raise ValueError("Duyuru başlığı ve metni boş olamaz.")
                    con.execute("UPDATE announcements SET title=?, body=? WHERE id=?", (title, body, aid))
                    flash("Duyuru güncellendi.", "success")
                elif action == "delete_announcement":
                    con.execute("DELETE FROM announcements WHERE id=?", (request.form.get("announcement_id"),))
                else:
                    flash("Bilinmeyen işlem.", "error")
        except ValueError as e:
            flash(str(e) or "Bilgileri kontrol et. BO3 skoru 2-0 veya 2-1 olmalı.", "error")
        except Exception:
            app.logger.exception("Yönetim işlemi başarısız")
            flash("İşlem tamamlanamadı. Bilgileri kontrol edip tekrar dene.", "error")
        return redirect(url_for("admin"))
    with db() as con:
        pending = con.execute("SELECT * FROM teams WHERE status='pending' ORDER BY created_at").fetchall()
        teams = con.execute("SELECT * FROM teams WHERE status='approved' ORDER BY COALESCE(team_number, 99), class_name").fetchall()
        all_teams = con.execute("SELECT * FROM teams ORDER BY COALESCE(team_number, 99), class_name").fetchall()
        matches, rounds = load_matches(con)
        announcements = con.execute("SELECT * FROM announcements ORDER BY id DESC").fetchall()
        applications_open = get_setting(con, "applications_open", "true") == "true"
    return render_template("admin.html", pending=pending, teams=teams, all_teams=all_teams, matches=matches, rounds=rounds,
                           announcements=announcements, applications_open=applications_open, team_colors=TEAM_COLORS)

