import os
import sqlite3
from pathlib import Path
from flask import Flask, render_template, request, redirect, url_for, flash, session

app = Flask(__name__)
app.secret_key = os.environ.get("SECRET_KEY", "local-demo-only-change-me")
DB_PATH = Path(__file__).with_name("ccsal_espor.db")
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()

class Database:
    """Small adapter so the same app works with local SQLite or hosted PostgreSQL."""
    def __init__(self):
        self.is_postgres = bool(DATABASE_URL)

    def __enter__(self):
        if self.is_postgres:
            import psycopg
            from psycopg.rows import dict_row
            url = DATABASE_URL
            if url.startswith("postgres://"):
                url = "postgresql://" + url[len("postgres://"):]
            if "sslmode=" not in url:
                url += ("&" if "?" in url else "?") + "sslmode=require"
            self.conn = psycopg.connect(url, row_factory=dict_row)
        else:
            self.conn = sqlite3.connect(DB_PATH)
            self.conn.row_factory = sqlite3.Row
        return self

    def execute(self, sql, params=()):
        if self.is_postgres:
            sql = sql.replace("?", "%s")
        return self.conn.execute(sql, params)

    def __exit__(self, exc_type, exc, tb):
        try:
            if exc_type is None:
                self.conn.commit()
            else:
                self.conn.rollback()
        finally:
            self.conn.close()
        return False

def db():
    return Database()

def init_db():
    with db() as con:
        if con.is_postgres:
            con.execute("""
                CREATE TABLE IF NOT EXISTS teams (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    class_name TEXT NOT NULL UNIQUE,
                    captain TEXT NOT NULL,
                    contact TEXT NOT NULL,
                    player1 TEXT NOT NULL,
                    player2 TEXT NOT NULL,
                    player3 TEXT NOT NULL,
                    player4 TEXT NOT NULL,
                    player5 TEXT NOT NULL,
                    substitute TEXT NOT NULL,
                    note TEXT DEFAULT '',
                    status TEXT NOT NULL DEFAULT 'pending',
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """)
            con.execute("""
                CREATE TABLE IF NOT EXISTS results (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    team_a BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
                    team_b BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
                    score_a INTEGER NOT NULL,
                    score_b INTEGER NOT NULL,
                    note TEXT DEFAULT '',
                    UNIQUE(team_a, team_b)
                )
            """)
        else:
            con.execute("""
                CREATE TABLE IF NOT EXISTS teams (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    class_name TEXT NOT NULL UNIQUE,
                    captain TEXT NOT NULL,
                    contact TEXT NOT NULL,
                    player1 TEXT NOT NULL,
                    player2 TEXT NOT NULL,
                    player3 TEXT NOT NULL,
                    player4 TEXT NOT NULL,
                    player5 TEXT NOT NULL,
                    substitute TEXT NOT NULL,
                    note TEXT DEFAULT '',
                    status TEXT NOT NULL DEFAULT 'pending',
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """)
            con.execute("""
                CREATE TABLE IF NOT EXISTS results (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    team_a INTEGER NOT NULL,
                    team_b INTEGER NOT NULL,
                    score_a INTEGER NOT NULL,
                    score_b INTEGER NOT NULL,
                    note TEXT DEFAULT '',
                    UNIQUE(team_a, team_b),
                    FOREIGN KEY(team_a) REFERENCES teams(id),
                    FOREIGN KEY(team_b) REFERENCES teams(id)
                )
            """)

# Create tables on local startup and on hosted deployment.
init_db()

@app.route("/")
def index():
    with db() as con:
        teams = con.execute("SELECT * FROM teams WHERE status='approved' ORDER BY class_name").fetchall()
        pending_count = con.execute("SELECT COUNT(*) AS count FROM teams WHERE status='pending'").fetchone()["count"]
        results = con.execute("""
            SELECT r.*, a.class_name AS a_name, b.class_name AS b_name
            FROM results r
            JOIN teams a ON a.id=r.team_a
            JOIN teams b ON b.id=r.team_b
            ORDER BY r.id DESC
        """).fetchall()
    stats = {t["id"]: {"team": t, "played": 0, "wins": 0, "losses": 0, "points": 0, "maps_for": 0, "maps_against": 0} for t in teams}
    for r in results:
        if r["team_a"] in stats and r["team_b"] in stats:
            a, b = stats[r["team_a"]], stats[r["team_b"]]
            a["played"] += 1
            b["played"] += 1
            a["maps_for"] += r["score_a"]
            a["maps_against"] += r["score_b"]
            b["maps_for"] += r["score_b"]
            b["maps_against"] += r["score_a"]
            if r["score_a"] > r["score_b"]:
                a["wins"] += 1
                a["points"] += 3
                b["losses"] += 1
            else:
                b["wins"] += 1
                b["points"] += 3
                a["losses"] += 1
    standings = sorted(stats.values(), key=lambda x: (x["points"], x["wins"], x["maps_for"]-x["maps_against"]), reverse=True)
    return render_template("index.html", teams=teams, results=results, standings=standings, pending_count=pending_count)

@app.route("/basvuru", methods=["GET", "POST"])
def apply():
    if request.method == "POST":
        fields = ["class_name", "captain", "contact", "player1", "player2", "player3", "player4", "player5", "substitute"]
        values = [request.form.get(k, "").strip() for k in fields]
        note = request.form.get("note", "").strip()
        if any(not v for v in values):
            flash("Lütfen zorunlu alanların tamamını doldurun.", "error")
            return render_template("apply.html")
        try:
            with db() as con:
                con.execute("""INSERT INTO teams
                (class_name,captain,contact,player1,player2,player3,player4,player5,substitute,note)
                VALUES (?,?,?,?,?,?,?,?,?,?)""", values + [note])
            flash("Başvurun alındı! Yönetici onayından sonra takım listesinde görünecek.", "success")
            return redirect(url_for("apply"))
        except Exception as e:
            # Unique class name conflict is the expected database error here.
            if "unique" in str(e).lower() or "duplicate" in str(e).lower():
                flash("Bu sınıf için daha önce başvuru yapılmış. Düzenleme için turnuva yöneticisiyle iletişime geçin.", "error")
            else:
                app.logger.exception("Başvuru kaydedilemedi")
                flash("Başvuru kaydedilemedi. Lütfen daha sonra tekrar deneyin.", "error")
    return render_template("apply.html")

def admin_authorized():
    if session.get("admin_logged_in"):
        return True
    expected = os.environ.get("ADMIN_KEY", "")
    supplied = request.args.get("key", "") or request.form.get("key", "")
    if expected and supplied == expected:
        session["admin_logged_in"] = True
        return True
    return False

@app.route("/yonetim", methods=["GET", "POST"])
def admin():
    if not admin_authorized():
        return render_template("admin_login.html")
    password = os.environ.get("ADMIN_KEY", "")
    if request.method == "POST":
        action = request.form.get("action")
        with db() as con:
            if action in ("approve", "reject"):
                status = "approved" if action == "approve" else "rejected"
                con.execute("UPDATE teams SET status=? WHERE id=?", (status, request.form.get("team_id")))
            elif action == "result":
                try:
                    a = int(request.form["team_a"])
                    b = int(request.form["team_b"])
                    sa = int(request.form["score_a"])
                    sb = int(request.form["score_b"])
                    if a == b or min(sa, sb) < 0 or max(sa, sb) > 2 or sa == sb or max(sa, sb) != 2:
                        flash("BO3 sonucu 2-0 veya 2-1 olmalı.", "error")
                    else:
                        con.execute("""INSERT INTO results(team_a,team_b,score_a,score_b,note)
                            VALUES(?,?,?,?,?) ON CONFLICT(team_a,team_b) DO UPDATE SET
                            score_a=excluded.score_a, score_b=excluded.score_b, note=excluded.note""",
                            (a,b,sa,sb,request.form.get("note","").strip()))
                        flash("Maç sonucu kaydedildi.", "success")
                except (ValueError, KeyError):
                    flash("Lütfen geçerli maç sonucu girin.", "error")
            elif action == "delete_result":
                con.execute("DELETE FROM results WHERE id=?", (request.form.get("result_id"),))
        if action is None:
            return redirect(url_for("admin"))
        return redirect(url_for("admin"))
    with db() as con:
        pending = con.execute("SELECT * FROM teams WHERE status='pending' ORDER BY created_at").fetchall()
        teams = con.execute("SELECT * FROM teams WHERE status='approved' ORDER BY class_name").fetchall()
        results = con.execute("""SELECT r.*, a.class_name AS a_name, b.class_name AS b_name
          FROM results r JOIN teams a ON a.id=r.team_a JOIN teams b ON b.id=r.team_b ORDER BY r.id DESC""").fetchall()
    return render_template("admin.html", pending=pending, teams=teams, results=results, key=password)

