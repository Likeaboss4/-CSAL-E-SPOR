DB_PATH = Path(__file__).with_name("ccsal_espor.db")
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()

class Database:
    """SQLite locally, PostgreSQL on the hosted deployment."""
    def __init__(self):
        self.is_postgres = bool(DATABASE_URL)

    def __enter__(self):
        if self.is_postgres:
            import psycopg
            from psycopg.rows import dict_row
            url = DATABASE_URL
            if url.startswith("postgres://"):
                url = "postgresql://" + url[len("postgres://"):]
            if "sslmode=" not in url:
                url += ("&" if "?" in url else "?") + "sslmode=require"
            self.conn = psycopg.connect(url, row_factory=dict_row)
        else:
            self.conn = sqlite3.connect(DB_PATH)
            self.conn.row_factory = sqlite3.Row
            self.conn.execute("PRAGMA foreign_keys = ON")
        return self

    def execute(self, sql, params=()):
        if self.is_postgres:
            sql = sql.replace("?", "%s")
        return self.conn.execute(sql, params)

    def __exit__(self, exc_type, exc, tb):
        try:
            self.conn.commit() if exc_type is None else self.conn.rollback()
        finally:
            self.conn.close()
        return False

def db():
    return Database()

def init_db():
    with db() as con:
        if con.is_postgres:
            con.execute("""CREATE TABLE IF NOT EXISTS teams (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                class_name TEXT NOT NULL UNIQUE, captain TEXT NOT NULL, contact TEXT NOT NULL,
                player1 TEXT NOT NULL, player2 TEXT NOT NULL, player3 TEXT NOT NULL,
                player4 TEXT NOT NULL, player5 TEXT NOT NULL, substitute TEXT NOT NULL,
                note TEXT DEFAULT '', status TEXT NOT NULL DEFAULT 'pending',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)""")
            con.execute("""CREATE TABLE IF NOT EXISTS results (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                team_a BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
                team_b BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
                score_a INTEGER NOT NULL, score_b INTEGER NOT NULL, note TEXT DEFAULT '',
                UNIQUE(team_a, team_b))""")
        else:
            con.execute("""CREATE TABLE IF NOT EXISTS teams (
                id INTEGER PRIMARY KEY AUTOINCREMENT, class_name TEXT NOT NULL UNIQUE,
                captain TEXT NOT NULL, contact TEXT NOT NULL, player1 TEXT NOT NULL,
                player2 TEXT NOT NULL, player3 TEXT NOT NULL, player4 TEXT NOT NULL,
                player5 TEXT NOT NULL, substitute TEXT NOT NULL, note TEXT DEFAULT '',
                status TEXT NOT NULL DEFAULT 'pending', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)""")
            con.execute("""CREATE TABLE IF NOT EXISTS results (
                id INTEGER PRIMARY KEY AUTOINCREMENT, team_a INTEGER NOT NULL, team_b INTEGER NOT NULL,
                score_a INTEGER NOT NULL, score_b INTEGER NOT NULL, note TEXT DEFAULT '',
                UNIQUE(team_a, team_b), FOREIGN KEY(team_a) REFERENCES teams(id),
                FOREIGN KEY(team_b) REFERENCES teams(id))""")

def init_tournament_tables():
    with db() as con:
        if con.is_postgres:
            con.execute("""CREATE TABLE IF NOT EXISTS matches (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, round_no INTEGER NOT NULL,
                slot_no INTEGER NOT NULL, team_a BIGINT REFERENCES teams(id) ON DELETE SET NULL,
                team_b BIGINT REFERENCES teams(id) ON DELETE SET NULL, score_a INTEGER, score_b INTEGER,
                match_date TEXT DEFAULT '', match_time TEXT DEFAULT '',
                status TEXT NOT NULL DEFAULT 'upcoming', note TEXT DEFAULT '',
                UNIQUE(round_no, slot_no))""")
            con.execute("""CREATE TABLE IF NOT EXISTS announcements (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title TEXT NOT NULL,
                body TEXT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)""")
        else:
            con.execute("""CREATE TABLE IF NOT EXISTS matches (
                id INTEGER PRIMARY KEY AUTOINCREMENT, round_no INTEGER NOT NULL, slot_no INTEGER NOT NULL,
                team_a INTEGER REFERENCES teams(id) ON DELETE SET NULL,
                team_b INTEGER REFERENCES teams(id) ON DELETE SET NULL, score_a INTEGER, score_b INTEGER,
                match_date TEXT DEFAULT '', match_time TEXT DEFAULT '',
                status TEXT NOT NULL DEFAULT 'upcoming', note TEXT DEFAULT '',
                UNIQUE(round_no, slot_no))""")
            con.execute("""CREATE TABLE IF NOT EXISTS announcements (
                id INTEGER PRIMARY KEY AUTOINCREMENT, title TEXT NOT NULL,
                body TEXT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)""")

def seed_bracket():
    # Safe, idempotent: never deletes or resets existing matches.
    with db() as con:
        for rnd, count in ((1, 4), (2, 2), (3, 1)):
            for slot in range(1, count + 1):
                con.execute("INSERT INTO matches(round_no,slot_no) VALUES(?,?) ON CONFLICT(round_no,slot_no) DO NOTHING", (rnd, slot))

init_db()
init_tournament_tables()
seed_bracket()

def load_matches(con):
    rows = con.execute("""SELECT m.*, a.class_name AS a_name, b.class_name AS b_name
        FROM matches m LEFT JOIN teams a ON a.id=m.team_a LEFT JOIN teams b ON b.id=m.team_b
        ORDER BY m.round_no,m.slot_no""").fetchall()
    rounds = {1: [], 2: [], 3: []}
    for m in rows:
        if m["round_no"] in rounds:
            rounds[m["round_no"]].append(m)
    return rows, rounds

@app.route("/")
def index():
    with db() as con:
        teams = con.execute("SELECT * FROM teams WHERE status='approved' ORDER BY class_name").fetchall()
        pending_count = con.execute("SELECT COUNT(*) AS count FROM teams WHERE status='pending'").fetchone()["count"]
        results = con.execute("""SELECT r.*,a.class_name AS a_name,b.class_name AS b_name
            FROM results r JOIN teams a ON a.id=r.team_a JOIN teams b ON b.id=r.team_b ORDER BY r.id DESC""").fetchall()
        matches, rounds = load_matches(con)
        announcements = con.execute("SELECT * FROM announcements ORDER BY id DESC").fetchall()
    return render_template("index.html", teams=teams, results=results, rounds=rounds,
                           matches=matches, announcements=announcements, pending_count=pending_count)

@app.route("/basvuru", methods=["GET", "POST"])
def apply():
    if request.method == "POST":
        fields = ["class_name","captain","contact","player1","player2","player3","player4","player5","substitute"]
        values = [request.form.get(k, "").strip() for k in fields]
        note = request.form.get("note", "").strip()
        if any(not v for v in values):
            flash("Lütfen zorunlu alanların tamamını doldurun.", "error")
            return render_template("apply.html")
        try:
            with db() as con:
                con.execute("""INSERT INTO teams
                    (class_name,captain,contact,player1,player2,player3,player4,player5,substitute,note)
                    VALUES(?,?,?,?,?,?,?,?,?,?)""", values + [note])
            flash("Başvurun alındı! Yönetici onayından sonra takım listesinde görünecek.", "success")
            return redirect(url_for("apply"))
        except Exception as e:
            if "unique" in str(e).lower() or "duplicate" in str(e).lower():
                flash("Bu sınıf için daha önce başvuru yapılmış.", "error")
            else:
                app.logger.exception("Başvuru kaydedilemedi")
                flash("Başvuru kaydedilemedi. Lütfen daha sonra tekrar deneyin.", "error")
    return render_template("apply.html")

def admin_authorized():
    if session.get("admin_logged_in"):
        return True
    expected = os.environ.get("ADMIN_KEY", "")
    supplied = request.form.get("key", "") or request.args.get("key", "")
    if expected and supplied == expected:
        session["admin_logged_in"] = True
        return True
    return False

def advance_winner(con, match, winner):
    if match["round_no"] >= 3:
        return
    next_round = match["round_no"] + 1
    next_slot = (match["slot_no"] + 1) // 2
    column = "team_a" if match["slot_no"] % 2 else "team_b"
    # Do not overwrite an already-played next-round match silently.
    nxt = con.execute("SELECT * FROM matches WHERE round_no=? AND slot_no=?", (next_round, next_slot)).fetchone()
    if nxt:
        if nxt["status"] == "completed":
            raise ValueError("Sonraki tur maçı tamamlanmış; önce o maçın sonucunu düzeltin.")
        other_col = "team_b" if column == "team_a" else "team_a"
        if nxt[other_col] == winner:
            pass
        con.execute(f"UPDATE matches SET {column}=? WHERE round_no=? AND slot_no=?", (winner, next_round, next_slot))
    else:
        con.execute(f"INSERT INTO matches(round_no,slot_no,{column}) VALUES(?,?,?)", (next_round,next_slot,winner))

@app.route("/yonetim", methods=["GET", "POST"])
def admin():
    if not admin_authorized():
        return render_template("admin_login.html")
    if request.method == "POST":
        action = request.form.get("action")
        try:
            with db() as con:
                if action in ("approve", "reject"):
                    status = "approved" if action == "approve" else "rejected"
                    con.execute("UPDATE teams SET status=? WHERE id=?", (status, request.form.get("team_id")))
                    flash("Başvuru durumu güncellendi.", "success")
                elif action == "save_match":
                    rnd, slot = int(request.form["round_no"]), int(request.form["slot_no"])
                    ta, tb = request.form.get("team_a") or None, request.form.get("team_b") or None
                    if rnd not in (1,2,3) or slot < 1 or slot > {1:4,2:2,3:1}[rnd] or (ta and ta == tb):
                        raise ValueError()
                    con.execute("""INSERT INTO matches(round_no,slot_no,team_a,team_b,match_date,match_time,status,note)
                        VALUES(?,?,?,?,?,?,?,?) ON CONFLICT(round_no,slot_no) DO UPDATE SET
                        team_a=excluded.team_a,team_b=excluded.team_b,match_date=excluded.match_date,
                        match_time=excluded.match_time,status=excluded.status,note=excluded.note""",
                        (rnd,slot,ta,tb,request.form.get("match_date",""),request.form.get("match_time",""),
                         request.form.get("status","upcoming"),request.form.get("note","").strip()))
                    flash("Eşleşme ve maç bilgileri kaydedildi.", "success")
                elif action == "match_result":
                    mid, sa, sb = int(request.form["match_id"]), int(request.form["score_a"]), int(request.form["score_b"])
                    if min(sa,sb) < 0 or max(sa,sb) > 2 or sa == sb or max(sa,sb) != 2:
                        raise ValueError()
                    match = con.execute("SELECT * FROM matches WHERE id=?", (mid,)).fetchone()
                    if not match or not match["team_a"] or not match["team_b"]:
                        raise ValueError()
                    winner = match["team_a"] if sa > sb else match["team_b"]
                    # Prevent editing a result if a downstream match has already been completed.
                    if match["round_no"] < 3:
                        nr, ns = match["round_no"] + 1, (match["slot_no"] + 1)//2
                        nxt = con.execute("SELECT * FROM matches WHERE round_no=? AND slot_no=?", (nr,ns)).fetchone()
                        col = "team_a" if match["slot_no"] % 2 else "team_b"
                        if nxt and nxt["status"] == "completed" and nxt[col] != winner:
                            raise ValueError("Sonraki tur tamamlanmış; önce sonraki tur sonucunu sıfırlayın.")
                    con.execute("UPDATE matches SET score_a=?,score_b=?,status='completed' WHERE id=?", (sa,sb,mid))
                    advance_winner(con, match, winner)
                    flash("Skor kaydedildi; kazanan sonraki tura aktarıldı.", "success")
                elif action == "delete_match_result":
                    mid = int(request.form["match_id"])
                    match = con.execute("SELECT * FROM matches WHERE id=?", (mid,)).fetchone()
                    if match:
                        if match["round_no"] < 3:
                            nr, ns = match["round_no"] + 1, (match["slot_no"] + 1)//2
                            col = "team_a" if match["slot_no"] % 2 else "team_b"
                            nxt = con.execute("SELECT * FROM matches WHERE round_no=? AND slot_no=?", (nr,ns)).fetchone()
                            if nxt and nxt["status"] == "completed":
                                raise ValueError("Önce sonraki tur maçının sonucunu sıfırlayın.")
                            if nxt and match["score_a"] is not None and match["score_b"] is not None:
                                prior_winner = match["team_a"] if match["score_a"] > match["score_b"] else match["team_b"]
                                con.execute(f"UPDATE matches SET {col}=NULL WHERE round_no=? AND slot_no=? AND {col}=?", (nr,ns,prior_winner))
                        con.execute("UPDATE matches SET score_a=NULL,score_b=NULL,status='upcoming' WHERE id=?", (mid,))
                        flash("Maç skoru sıfırlandı.", "success")
                elif action == "announcement":
                    title, body = request.form.get("title","").strip(), request.form.get("body","").strip()
                    if not title or not body:
                        raise ValueError()
                    con.execute("INSERT INTO announcements(title,body) VALUES(?,?)", (title,body))
                    flash("Duyuru yayımlandı.", "success")
                elif action == "delete_announcement":
                    con.execute("DELETE FROM announcements WHERE id=?", (request.form.get("announcement_id"),))
                else:
                    flash("Bilinmeyen işlem.", "error")
        except ValueError as e:
            flash(str(e) or "Bilgileri kontrol et. BO3 skoru 2-0 veya 2-1 olmalı.", "error")
        except Exception:
            app.logger.exception("Yönetim işlemi başarısız")
            flash("İşlem tamamlanamadı. Bilgileri kontrol edip tekrar dene.", "error")
        return redirect(url_for("admin"))
    with db() as con:
        pending = con.execute("SELECT * FROM teams WHERE status='pending' ORDER BY created_at").fetchall()
        teams = con.execute("SELECT * FROM teams WHERE status='approved' ORDER BY class_name").fetchall()
        matches, rounds = load_matches(con)
        announcements = con.execute("SELECT * FROM announcements ORDER BY id DESC").fetchall()
    return render_template("admin.html", pending=pending, teams=teams, matches=matches, rounds=rounds,
                           announcements=announcements)

